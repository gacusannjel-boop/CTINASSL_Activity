export const worlds = worldGroups.map(({ songs, ...world }, worldIndex) => {
  const id = worldIndex + 1;
  const artStyles = [world.art, 'garden', 'city', 'joy', 'rose', 'blue', 'bubblegum', 'teddy', 'bratz'];

  return {
    ...world,
    id,
    tracks: songs.map(([song, artist], songIndex) => ({
      id: `${id}-${songIndex + 1}`,
      song,
      artist,
      world: world.name,
      mood: world.mood,
      art: artStyles[(songIndex + worldIndex) % artStyles.length],
    })),
  };
});

export const tracks = worlds.flatMap(world => world.tracks);

